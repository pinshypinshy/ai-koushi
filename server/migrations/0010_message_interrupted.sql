-- §5.7「ストリーミング中断：部分生成分を保存し、ユーザーに再生成ボタンを提示する」（Q-33）。
--
-- 途中で切れた応答は本文だけでは完了した応答と見分けられない。中断の事実を画面の
-- 一時的な状態にしか持たないと、再読み込みや講義の切り替えで再生成の導線が消え、
-- 途切れた発言が完了したものとして残る。
--
-- 再生成は失敗時と同じプロンプトを送り直す。そのために、途切れた発言を履歴から外し、
-- 成功時に置き換える対象として特定できる必要がある。
--
-- 既存の行は 0 になる。過去に途切れた発言を後から見分ける手段は無い。
ALTER TABLE messages ADD COLUMN interrupted INTEGER NOT NULL DEFAULT 0
  CHECK (interrupted IN (0, 1));
