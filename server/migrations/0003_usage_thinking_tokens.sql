-- 思考トークンを出力トークンから分離して記録する（§5.5「思考トークンの扱い」）。
--
-- Gemini 3系の思考トークンは課金上の出力に算入されるため output_tokens には含めたままとし、
-- この列はその内数を保持する。分離しないと、①②のコストが思考によるものか本文出力に
-- よるものか判別できず、思考の水準を下げるべきかどうかを判断できない。
-- 実測では①②の出力が §8.2.2 の見積もりの2〜4倍に達しており、内訳の把握が要る。
ALTER TABLE ai_usage_logs ADD COLUMN thinking_tokens INTEGER NOT NULL DEFAULT 0;
