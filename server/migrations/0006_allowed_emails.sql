-- ログインを許可する Google アカウントの一覧（§4.6 利用者制限）。
--
-- 環境変数（ALLOWED_EMAILS）から移した。理由は2つある。
-- ・1件だけの追加ができる。Secrets は読み出せず上書きしかできないため、
--   1人足すたびに全員分を打ち直す必要があった
-- ・他人のメールアドレスを git の履歴に残さずに済む。設定ファイルに書くと
--   後から消しても履歴からは消えない
--
-- 値そのものは鍵ではない。漏れてもログインできるようにはならず、
-- 可否を決めるのは Google の認証の方である（判定条件を保持しているにすぎない）。
CREATE TABLE allowed_emails (
  -- 照合を単純にするため、小文字に正規化して保存する
  email      TEXT PRIMARY KEY,
  -- 誰のアドレスか分からなくなるのを防ぐための覚書。任意
  note       TEXT,
  created_at INTEGER NOT NULL
);
