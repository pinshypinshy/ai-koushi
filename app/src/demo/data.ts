/**
 * ログイン前に中身を見てもらうためのサンプル講義（「画面を見る」）。
 *
 * 実データと同じ型で扱えるよう、サーバーが返す表現へ demo/index.ts で組み替える。
 * ここは素材だけを持ち、正解と解説も保持する（採点の応答で使う）。
 */

export interface DemoStep {
  orderIndex: number
  title: string
  objective: string
  keyPoints: string[]
  /** AI の発話。1要素が1発話にあたる */
  script: string[]
}

export interface DemoChoice {
  body: string
  isCorrect: boolean
}

export interface DemoQuestion {
  stem: string
  explanation: string
  choices: DemoChoice[]
  /** 関連するステップの id。複数持つものが横断設問（§4.3.1.1） */
  coveredStepIds: string[]
}

function step(
  orderIndex: number,
  title: string,
  objective: string,
  keyPoints: string[],
  script: string[],
): DemoStep {
  return { orderIndex, title, objective, keyPoints, script }
}

function q(
  stem: string,
  explanation: string,
  choices: [string, boolean][],
  coveredStepIds: string[],
): DemoQuestion {
  return {
    stem,
    explanation,
    choices: choices.map(([body, isCorrect]) => ({ body, isCorrect })),
    coveredStepIds,
  }
}

