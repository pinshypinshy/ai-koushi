let seq = 0
const uid = (p: string) => `${p}-${++seq}`

function step(
  orderIndex: number,
  title: string,
  objective: string,
  keyPoints: string[],
  script: string[],
): Step {
  return {
    id: `step-${title}`,
    orderIndex,
    title,
    objective,
    keyPoints,
    status: 'not_started',
    script,
  }
}

function q(
  stem: string,
  explanation: string,
  choices: [string, boolean][],
  coveredStepIds: string[],
): Question {
  return {
    id: uid('q'),
    stem,
    explanation,
    choices: choices.map(([body, isCorrect]) => ({ id: uid('c'), body, isCorrect })),
    coveredStepIds,
  }
}

