function course(
  id: string,
  title: string,
  steps: Step[],
  questions: Question[],
  completedCount: number,
  updatedAt: number,
): Course {
  const s = steps.map((x, i) => ({
    ...x,
    id: x.id,
    status: (i < completedCount
      ? 'completed'
      : i === completedCount
        ? 'in_progress'
        : 'not_started') as Step['status'],
  }))
  const current = s[completedCount] ?? null
  return {
    id,
    title,
    status: 'ready',
    sourceMarkdown: SAMPLE_MARKDOWN,
    steps: s,
    questions,
    messages: current
      ? [{ id: uid('m'), stepId: current.id, role: 'assistant', content: current.script[0] }]
      : [],
    currentStepId: current?.id ?? null,
    scriptCursor: 1,
    updatedAt,
  }
}

